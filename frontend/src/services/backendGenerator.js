export async function createGeneratedBackendArchive({ projectName, schema, apiKey }) {
  const files = buildGeneratedBackendFiles({ projectName, schema, apiKey });
  const { default: JSZip } = await import("jszip");
  const zip = new JSZip();
  const folderName = (projectName.trim() || "schevo-backend")
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-|-$/g, "") || "schevo-backend";
  Object.entries(files).forEach(([path, content]) => zip.file(`${folderName}/${path}`, content));
  const blob = await zip.generateAsync({ type: "blob", mimeType: "application/zip" });
  return { blob, files, fileName: `${folderName}.zip` };
}
