import test from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { execPath } from "node:process";
import JSZip from "jszip";
import {
  buildGeneratedBackendFiles,
  createGeneratedBackendArchive,
  createProjectApiEndpoints,
  generateProjectApiKey,
} from "./backendGenerator.js";

const apiKey = `sch_${"a".repeat(64)}`;
const schema = {
  schemaVersion: 2,
  tables: [{
    id: "people",
    name: "people",
    columns: [
      { id: "person-id", name: "id", type: "uuid", nullable: false },
      { id: "person-name", name: "display_name", type: "text", nullable: false },
    ],
    constraints: [{ id: "people-pk", type: "primaryKey", columns: ["person-id"] }],
    indexes: [],
  }],
  relationships: [],
};

test("generates project-specific CRUD endpoint contracts", () => {
  assert.deepEqual(createProjectApiEndpoints(schema).map(({ method, path }) => `${method} ${path}`), [
    "GET /api/people",
    "POST /api/people",
    "GET /api/people/:key",
    "PATCH /api/people/:key",
    "DELETE /api/people/:key",
  ]);
});

test("generates a runnable scaffold with schema SQL, API key, docs, and tests", () => {
  const files = buildGeneratedBackendFiles({ projectName: "People App", schema, apiKey });
  assert.match(files[".env"], new RegExp(apiKey));
  assert.match(files[".gitignore"], /\.env/);
  assert.match(files["migrations/001_schema.sql"], /CREATE TABLE "people"/);
  assert.match(files["src/tables.js"], /"display_name"/);
  assert.match(files["src/api.js"], /router\.patch/);
  assert.match(files["README.md"], /GET \/api\/people/);
  assert.match(files["package.json"], /"test": "node --test"/);

  for (const [path, content] of Object.entries(files)) {
    if (!path.endsWith(".js")) continue;
    const result = spawnSync(execPath, ["--input-type=module", "--check"], { input: content, encoding: "utf8" });
    assert.equal(result.status, 0, `${path}: ${result.stderr}`);
  }
});

test("refuses generation when schema errors or missing primary keys prevent CRUD", () => {
  assert.throws(() => buildGeneratedBackendFiles({ projectName: "Empty", schema: { tables: [], relationships: [] }, apiKey }), /at least one table/i);
  assert.throws(() => buildGeneratedBackendFiles({
    projectName: "No key",
    schema: { ...schema, tables: [{ ...schema.tables[0], constraints: [] }] },
    apiKey,
  }), /primary key/i);
  assert.throws(() => buildGeneratedBackendFiles({ projectName: "Missing key", schema, apiKey: "bad" }), /valid generated API key/i);
});

test("creates a ZIP with generated project files", async () => {
  const archive = await createGeneratedBackendArchive({ projectName: "People App", schema, apiKey });
  const zip = await JSZip.loadAsync(archive.blob);
  assert.equal(archive.fileName, "people-app.zip");
  assert.ok(zip.file("people-app/src/server.js"));
  assert.ok(zip.file("people-app/.env"));
  assert.match(await zip.file("people-app/README.md").async("string"), /Generated by Schevo/);
});

test("generates a distinct high-entropy API key using secure randomness", () => {
  let filled = false;
  let generation = 0;
  const key = generateProjectApiKey({
    getRandomValues(bytes) {
      filled = true;
      generation += 1;
      bytes.forEach((_, index) => { bytes[index] = index + generation; });
      return bytes;
    },
  });
  const secondKey = generateProjectApiKey({
    getRandomValues(bytes) {
      generation += 1;
      bytes.forEach((_, index) => { bytes[index] = index + generation; });
      return bytes;
    },
  });
  assert.equal(filled, true);
  assert.match(key, /^sch_[a-f0-9]{64}$/);
  assert.notEqual(key, secondKey);
  assert.throws(() => generateProjectApiKey({}), /Secure random generation is unavailable/);
});
